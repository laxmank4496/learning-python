# Demonstration of different data types in Python

a = 10                  # Integer
b = 10.5                # Float
c = 2 + 3j              # Complex
d = True                # Boolean
e = "Python"            # String
f = [1, 2, 3]           # List
g = (1, 2, 3)           # Tuple
h = {1, 2, 3}            # Set
i = {"name": "Rahul"}   # Dictionary
j = None                # NoneType

print(a, type(a))
print(b, type(b))
print(c, type(c))
print(d, type(d))
print(e, type(e))
print(f, type(f))
print(g, type(g))
print(h, type(h))
print(i, type(i))
print(j, type(j))